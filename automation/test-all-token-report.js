'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const script=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gu)].map(m=>m[1]).find(s=>s.includes('root.GhostMapReports=api'));
const context={};vm.createContext(context);vm.runInContext(script,context);
const R=context.GhostMapReports;
const c={chapter:'测试',source_units:[{text:'之风风。',tokens:[[0,1],[1,2],[2,3],[3,4]]}]};
const m={ids:[0],view:()=>c};
const rows=R.allTokens(m);
assert.equal(rows.length,2);
assert.equal(rows.find(r=>r.word==='风').frequency,2);
assert.ok(rows.some(r=>r.word==='之'),'虚词也纳入统计');
assert.equal(R.allTokens(m,'1').length,0);
const revised={...c,segmentation_note:'之 / 风风 / 。'};
assert.ok(R.allTokens({ids:[0],view:()=>revised}).some(r=>r.word==='风风'));
assert.equal(R.allTokens({ids:[0],view:()=>revised}).length,2);
const rare={chapter:'异体字',source_units:[{text:'𪩸山',tokens:[[0,1],[1,2]]}]};
assert.equal(R.allTokens({ids:[0],view:()=>rare})[0].word,'𪩸');
console.log('PASS 全部词汇、虚词、标点过滤、分词修订与篇目筛选');
