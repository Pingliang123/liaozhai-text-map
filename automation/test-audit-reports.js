'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const A=require('../audit-reports.js');
const chapters=[{chapter_id:0,chapter:'甲',event_types:{人:1},places:[]},{chapter_id:33,chapter:'乙',event_types:{鬼:1,妖:1},places:[{word:'济南'}]},{chapter_id:34,chapter:'丙',event_types:{},places:[]}];
const model={ids:chapters.map(c=>c.chapter_id),view:id=>chapters.find(c=>c.chapter_id===id)};
const all=A.eventRows(model);assert.equal(all.length,3);const stats=A.eventStats(all);
assert.deepEqual(stats.counts,[['人',1],['鬼',1],['妖',1],['神',0],['未定',1]]);
assert.equal(stats.combinations.reduce((sum,r)=>sum+r[1],0),3);
assert.deepEqual(A.eventRows(model,'','济南','鬼').map(r=>r.chapter_id),[33]);
assert.equal(A.eventRows(model,'0').length,1);assert.equal(A.eventRows(model,'','','未定')[0].chapter_id,34);
assert.throws(()=>A.validateTypes(['人','鬼']));assert.deepEqual(A.validateTypes(['鬼','神']),{鬼:1,神:1});assert.deepEqual(A.validateTypes([]),{});
assert(A.csv([['=SUM(A1)','a"b']]).includes("'=SUM"));
const root=path.resolve(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('id="event-audit-reports"'));assert(html.includes('auditReports.render()'));assert(html.includes('audit-reports.js?v='));
const data=JSON.parse(fs.readFileSync(path.join(root,'assets/deepseek-review.json'),'utf8'));
assert.equal(data.protected_ids.length,33);assert(data.entries.length>8000);assert(data.entries.every(e=>!data.protected_ids.includes(e.chapter_id)));
assert(data.entries.some(e=>e.kind==='event'));assert(data.entries.some(e=>e.kind==='segmentation'));assert(data.entries.some(e=>e.state==='held'));
assert(!fs.readFileSync(path.join(root,'audit-reports.js'),'utf8').includes('AI 初审'));
console.log('PASS: editable event table, multi-label bars, exclusive-combination pie, CSV, all imported records and first-33 exclusion');
