'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const M = require('./ghost_map_model');
const { ALIASES, classify } = require('./audit-unmapped-place-equivalences');
assert.equal(classify('青州城').target, '青州');
assert.equal(classify('客金陵').target, '金陵');
assert.equal(classify('都中').target, '都');
assert.equal(classify('城隍庙').category, 'space-or-building');
assert.equal(classify('东村').category, 'context-needed');
assert.equal(classify('虚构词').category, 'unresolved');
assert(Object.keys(ALIASES).length >= 25);
const pack = JSON.parse(fs.readFileSync('data-package.json', 'utf8'));
const model = M.create(pack.base);
model.importDocument(JSON.parse(fs.readFileSync('manual-revisions.json', 'utf8')));
assert(model.places().some(row => row.name === model.placeName('都') && row.merged_names.includes('都')));
assert.equal(model.placeInfo('都').coordinate_kind,'approximate','原文都的定位精度仍保留');
assert(!Object.hasOwn(pack.base.name_aliases, '青州城'), '同篇已有“青州”时不应重复合并“青州城”');
assert(!Object.hasOwn(pack.base.name_aliases, '客金陵'), '同篇已有“金陵”时不应重复合并“客金陵”');
for(const id of model.ids){const words=model.view(id).places.map(p=>model.name(p.word));assert.equal(new Set(words).size,words.length,'首都别名归并后不应产生重复篇目地点');}
const report = JSON.parse(fs.readFileSync('reports/unmapped-place-equivalence-audit-20261019.json', 'utf8'));
assert(Number.isInteger(report.total_checked)&&report.total_checked>0);
assert.equal(report.total_checked, report.merged + report.covered_by_existing + report.remaining);
console.log('PASS unmapped place equivalence audit classification');
