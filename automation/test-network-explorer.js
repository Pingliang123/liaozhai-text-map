const assert=require('assert/strict'),X=require('../assets/research-lab/network-explorer');
const graph={nodes:['A','B','C','D','Z'].map(id=>({id,label:id,kind:'space'})),edges:[['A','B',2],['B','A',3],['C','A',4],['B','D',1],['A','A',1]].map(([source,target,weight])=>({source,target,weight,directed:true,evidence:[]}))};
const saved=JSON.stringify(graph),pairs=g=>g.edges.map(e=>e.source+e.target).sort();
assert.deepEqual(pairs(X.neighborhood(graph,'A',60,1,'out')),['AA','AB']);
assert.deepEqual(pairs(X.neighborhood(graph,'A',60,1,'in')),['AA','BA','CA']);
assert.deepEqual(pairs(X.neighborhood(graph,'A',60,2,'out')),['AA','AB','BA','BD']);
assert.deepEqual(pairs(X.neighborhood(graph,'A',60,1,'both')),['AA','AB','BA','CA']);
assert.equal(X.neighborhood(graph,'missing').nodes.length,0);
assert.equal(X.neighborhood(graph,'Z').nodes.length,1);
assert.deepEqual(X.neighborhood(graph,'A',2,1,'both').nodes.map(n=>n.id),['A','C']);
const undirected={...graph,edges:graph.edges.map(e=>({...e,directed:false}))};
assert.deepEqual(pairs(X.neighborhood(undirected,'A',60,1,'in')),pairs(X.neighborhood(undirected,'A',60,1,'out')));
const partition={A:0,B:0,C:1,D:1,Z:2};assert.deepEqual(pairs(X.groupView(graph,partition,0)),['AA','AB','BA']);assert.equal(X.groupView(graph,partition,2).nodes[0].id,'Z');
assert.equal(JSON.stringify(graph),saved,'Views must not change the analytical graph');
const a={id:'A',x:0,y:0},b={id:'B',x:200,y:0},forward=X.arrow(a,b,10,20),reverse=X.arrow(b,a,20,10),numbers=forward.match(/-?\d+(?:\.\d+)?/g).map(Number);
assert(Math.abs(Math.hypot(200-numbers[4],numbers[5])-24)<1e-8,'Arrow ends just outside target radius');
assert(forward.includes('Q100 22')&&reverse.includes('Q100 -22'),'Reverse edges use opposite curves');
assert(X.arrow(a,a,10,10).includes(' C'));assert(!X.arrow(a,{...b,x:0},10,20).includes('NaN'));
console.log('PASS directed one/two-hop views, strongest-first limits, isolated groups, immutable source and radius-aware arrows');
